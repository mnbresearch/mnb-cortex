/**
 * Regenerate docs/capability-register.json from the source.
 *
 *     npm run capability:snapshot
 *
 * Run this when a change to a module deliberately alters what it is connected
 * to, and commit the resulting diff alongside the change. The diff is the
 * point: it says, in review, which page got deeper or shallower.
 */

import { writeFileSync } from "node:fs";
import { scanAll } from "./lib/capability-scan.mjs";

const register = scanAll();
const out = new URL("../docs/capability-register.json", import.meta.url);

const counts = {};
for (const r of Object.values(register)) counts[r.depth] = (counts[r.depth] || 0) + 1;

writeFileSync(out, JSON.stringify({
  note: "GENERATED by scripts/capability-snapshot.mjs. Do not edit by hand — " +
        "run `npm run capability:snapshot` and commit the diff. " +
        "scripts/test-capability-register.mjs fails when this disagrees with the source.",
  generated_from: "src/app/(app)/**/page.tsx, one hop through imports and /api route handlers",
  totals: { modules: Object.keys(register).length, ...counts },
  modules: register,
}, null, 2) + "\n");

console.log(`capability register: ${Object.keys(register).length} modules written to docs/capability-register.json`);
for (const [d, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(3)}  ${d}`);
